//! Generates the command registry (`$OUT_DIR/commands_table.rs`) from `doc/menu-ui.csv`,
//! the export of the menu specification: the menu, the command palette and the shortcuts
//! all come from that one table (see `src/commands/`).

use std::fmt::Write as _;

/// The rows of a CSV file (RFC 4180: quoted fields may hold commas, quotes and newlines).
fn parse_csv(text: &str) -> Vec<Vec<String>> {
    let mut rows = Vec::new();
    let mut row = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match (quoted, c) {
            (true, '"') if chars.peek() == Some(&'"') => {
                chars.next();
                field.push('"');
            }
            (true, '"') => quoted = false,
            (true, c) => field.push(c),
            (false, '"') => quoted = true,
            (false, ',') => row.push(std::mem::take(&mut field)),
            (false, '\n') => {
                row.push(std::mem::take(&mut field));
                rows.push(std::mem::take(&mut row));
            }
            (false, '\r') => {}
            (false, c) => field.push(c),
        }
    }
    if !field.is_empty() || !row.is_empty() {
        row.push(field);
        rows.push(row);
    }
    rows
}

/// A shortcut cell is used only when it is a plain key chord ("F5", "Shift+F5",
/// "Ctrl+Shift+P", "F4 (window close)"); notes such as "F9 cycles" are not shortcuts.
fn shortcut(cell: &str) -> Option<String> {
    let chord = cell.split(" (").next()?.trim();
    let mut parts = chord.split('+').collect::<Vec<_>>();
    let key = parts.pop()?;
    let modifiers_ok = parts.iter().all(|m| matches!(*m, "Ctrl" | "Shift" | "Alt"));
    let key_ok =
        (key.len() >= 2 && key.starts_with('F') && key[1..].chars().all(|c| c.is_ascii_digit()))
            || (key.len() == 1 && key.chars().all(|c| c.is_ascii_uppercase()));
    (modifiers_ok && key_ok).then(|| chord.to_owned())
}

fn main() {
    println!("cargo:rerun-if-changed=doc/menu-ui.csv");
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string("doc/menu-ui.csv").expect("doc/menu-ui.csv");
    let rows = parse_csv(&text);
    let mut out = String::from(
        "// Generated by build.rs from doc/menu-ui.csv: do not edit.\n\
         pub static COMMANDS: &[CommandSpec] = &[\n",
    );
    let mut seen = std::collections::HashSet::new();
    for row in rows.iter().skip(1) {
        let cell = |i: usize| row.get(i).map(|s| s.trim()).unwrap_or("");
        let id = cell(4);
        if id.is_empty() {
            continue;
        }
        assert!(seen.insert(id.to_owned()), "doc/menu-ui.csv: {id} twice");
        let path: Vec<&str> = (0..4).map(cell).filter(|s| !s.is_empty()).collect();
        let kind = match cell(8) {
            "act" => "Kind::Action",
            "tog" => "Kind::Toggle",
            "rad" => "Kind::Radio",
            "inp" => "Kind::Input",
            "ss" => "Kind::StartStop",
            "sub" => "Kind::Submenu",
            other => panic!("doc/menu-ui.csv: {id}: unknown type {other:?}"),
        };
        let stop = cell(5);
        let _ = writeln!(
            out,
            "    CommandSpec {{ id: {id:?}, path: &{path:?}, kind: {kind}, stop_id: {stop}, \
             shortcut: {shortcut}, aim: {aim:?}, note: {note:?} }},",
            stop = if stop.is_empty() {
                "None".into()
            } else {
                format!("Some({stop:?})")
            },
            shortcut = match shortcut(cell(9)) {
                Some(s) => format!("Some({s:?})"),
                None => "None".into(),
            },
            aim = cell(6),
            note = cell(7),
        );
    }
    out.push_str("];\n");
    let dest = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("commands_table.rs");
    std::fs::write(dest, out).unwrap();
}
