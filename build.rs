//! Generates the command registry (`$OUT_DIR/commands_table.rs`) from `doc/menu-ui.csv`,
//! the export of the menu specification: the menu, the command palette and the shortcuts
//! all come from that one table (see `src/commands/`).

use std::fmt::Write as _;

/// The rows of a CSV file (RFC 4180: quoted fields may hold commas, quotes and newlines).
fn parse_csv(text: &str) -> Vec<Vec<String>> {
    let mut rows = Vec::new();
    let mut row = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match (quoted, c) {
            (true, '"') if chars.peek() == Some(&'"') => {
                chars.next();
                field.push('"');
            }
            (true, '"') => quoted = false,
            (true, c) => field.push(c),
            (false, '"') => quoted = true,
            (false, ',') => row.push(std::mem::take(&mut field)),
            (false, '\n') => {
                row.push(std::mem::take(&mut field));
                rows.push(std::mem::take(&mut row));
            }
            (false, '\r') => {}
            (false, c) => field.push(c),
        }
    }
    if !field.is_empty() || !row.is_empty() {
        row.push(field);
        rows.push(row);
    }
    rows
}

/// A shortcut cell is used only when it is a plain key chord ("F5", "Shift+F5",
/// "Ctrl+Shift+P", "F4 (window close)"); notes such as "F9 cycles" are not shortcuts.
fn shortcut(cell: &str) -> Option<String> {
    let chord = cell.split(" (").next()?.trim();
    let mut parts = chord.split('+').collect::<Vec<_>>();
    let key = parts.pop()?;
    let modifiers_ok = parts.iter().all(|m| matches!(*m, "Ctrl" | "Shift" | "Alt"));
    let key_ok =
        (key.len() >= 2 && key.starts_with('F') && key[1..].chars().all(|c| c.is_ascii_digit()))
            || (key.len() == 1 && key.chars().all(|c| c.is_ascii_uppercase()));
    (modifiers_ok && key_ok).then(|| chord.to_owned())
}

/// CubeCL's CPU backend links a prebuilt LLVM that exists for these targets only (and not for a
/// web page): the same condition as the target table of `Cargo.toml` that asks for it.
fn cubecl_cpu_backend() -> bool {
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    std::env::var_os("CARGO_FEATURE_CRT_GPU").is_some()
        && matches!(
            (os.as_str(), arch.as_str()),
            ("linux", "x86_64" | "aarch64") | ("macos", "aarch64") | ("windows", "x86_64")
        )
}

/// `third_party/licenses.json` (1.6 MB of licence texts) gzipped into `$OUT_DIR/licenses.json.gz`:
/// what the executable embeds for Help > Third-party licences (`src/ui/licences.rs`), a tenth of
/// the size, decompressed when the program starts.
fn compress_licences() {
    use std::io::Write;
    println!("cargo:rerun-if-changed=third_party/licenses.json");
    let json = std::fs::read("third_party/licenses.json").expect("third_party/licenses.json");
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("licenses.json.gz");
    let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
    encoder.write_all(&json).unwrap();
    std::fs::write(out, encoder.finish().unwrap()).unwrap();
}

fn main() {
    compress_licences();
    println!("cargo::rustc-check-cfg=cfg(crt_cpu)");
    if cubecl_cpu_backend() {
        println!("cargo:rustc-cfg=crt_cpu");
    }
    println!("cargo:rerun-if-changed=doc/menu-ui.csv");
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string("doc/menu-ui.csv").expect("doc/menu-ui.csv");
    let rows = parse_csv(&text);
    let mut out = String::from(
        "// Generated by build.rs from doc/menu-ui.csv: do not edit.\n\
         pub static COMMANDS: &[CommandSpec] = &[\n",
    );
    let mut seen = std::collections::HashSet::new();
    // a `sep` row: a line in its menu before the next item there (the menu's depth: its path)
    let mut separators: Vec<(String, usize)> = Vec::new();
    let mut pending_separator: Option<usize> = None;
    // the configuration's radio groups (column `Config`: `order:key`, `*` after the default)
    let mut config_groups: Vec<(usize, String, Vec<String>, Option<String>)> = Vec::new();
    // the configuration's values (an input's `key`)
    let mut config_values: Vec<(String, String)> = Vec::new();
    // the configuration's switches (a toggle's `key`)
    let mut config_toggles: Vec<(String, String)> = Vec::new();
    for row in rows.iter().skip(1) {
        let cell = |i: usize| row.get(i).map(|s| s.trim()).unwrap_or("");
        if cell(8) == "sep" {
            pending_separator = Some((0..4).map(cell).filter(|s| !s.is_empty()).count());
            continue;
        }
        let id = cell(4);
        if id.is_empty() {
            continue;
        }
        if let Some(depth) = pending_separator.take() {
            separators.push((id.to_owned(), depth));
        }
        assert!(seen.insert(id.to_owned()), "doc/menu-ui.csv: {id} twice");
        let path: Vec<&str> = (0..4).map(cell).filter(|s| !s.is_empty()).collect();
        let kind = match cell(8) {
            "act" => "Kind::Action",
            "tog" => "Kind::Toggle",
            "rad" => "Kind::Radio",
            "inp" => "Kind::Input",
            "ss" => "Kind::StartStop",
            "sub" => "Kind::Submenu",
            other => panic!("doc/menu-ui.csv: {id}: unknown type {other:?}"),
        };
        let config = cell(10);
        if !config.is_empty() && kind == "Kind::Input" {
            config_values.push((config.to_owned(), id.to_owned()));
        } else if !config.is_empty() && kind == "Kind::Toggle" {
            config_toggles.push((config.to_owned(), id.to_owned()));
        } else if !config.is_empty() {
            assert_eq!(kind, "Kind::Radio", "doc/menu-ui.csv: {id}: only a radio item, an input or a toggle has a Config");
            let (order, key) = config
                .split_once(':')
                .unwrap_or_else(|| panic!("doc/menu-ui.csv: {id}: Config is order:key"));
            let order: usize = order
                .parse()
                .unwrap_or_else(|_| panic!("doc/menu-ui.csv: {id}: Config order {order:?}"));
            let (key, is_default) = match key.strip_suffix('*') {
                Some(key) => (key, true),
                None => (key, false),
            };
            let at = match config_groups.iter().position(|g| g.1 == key) {
                Some(at) => at,
                None => {
                    config_groups.push((order, key.to_owned(), Vec::new(), None));
                    config_groups.len() - 1
                }
            };
            let group = &mut config_groups[at];
            assert_eq!(group.0, order, "doc/menu-ui.csv: {id}: the order of {key} changes");
            group.2.push(id.to_owned());
            if is_default {
                assert!(group.3.replace(id.to_owned()).is_none(), "doc/menu-ui.csv: {key} has two defaults");
            }
        }
        let stop = cell(5);
        let _ = writeln!(
            out,
            "    CommandSpec {{ id: {id:?}, path: &{path:?}, kind: {kind}, stop_id: {stop}, \
             shortcut: {shortcut}, aim: {aim:?}, note: {note:?} }},",
            stop = if stop.is_empty() {
                "None".into()
            } else {
                format!("Some({stop:?})")
            },
            shortcut = match shortcut(cell(9)) {
                Some(s) => format!("Some({s:?})"),
                None => "None".into(),
            },
            aim = cell(6),
            note = cell(7),
        );
    }
    out.push_str("];\n");
    out.push_str(
        "/// The menu separators: a line before command `id` in the menu of depth `depth`.\n\
         pub static SEPARATORS: &[(&str, usize)] = &[\n",
    );
    for (id, depth) in &separators {
        let _ = writeln!(out, "    ({id:?}, {depth}),");
    }
    out.push_str("];\n");
    out.push_str(
        "/// The radio groups a configuration keeps, in the order they are applied: the key, the \
         commands of the items, the default one.\n\
         pub static CONFIG_GROUPS: &[ConfigGroup] = &[\n",
    );
    config_groups.sort_by_key(|group| group.0);
    for (_, key, items, default) in &config_groups {
        let default = default
            .as_deref()
            .unwrap_or_else(|| panic!("doc/menu-ui.csv: {key} has no default (a * in Config)"));
        let _ = writeln!(
            out,
            "    ConfigGroup {{ key: {key:?}, items: &{items:?}, default: {default:?} }},"
        );
    }
    out.push_str("];\n");
    out.push_str(
        "/// The values a configuration keeps, each set by an input command (its argument).\n\
         pub static CONFIG_VALUES: &[ConfigValue] = &[\n",
    );
    for (key, id) in &config_values {
        let _ = writeln!(out, "    ConfigValue {{ key: {key:?}, id: {id:?} }},");
    }
    out.push_str("];\n");
    out.push_str(
        "/// The switches a configuration keeps, each flipped by a toggle command.\n\
         pub static CONFIG_TOGGLES: &[ConfigValue] = &[\n",
    );
    for (key, id) in &config_toggles {
        let _ = writeln!(out, "    ConfigValue {{ key: {key:?}, id: {id:?} }},");
    }
    out.push_str("];\n");
    let dest = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("commands_table.rs");
    std::fs::write(dest, out).unwrap();
}
